"""Pydantic v2 data models and API schemas."""

from typing import List, Optional
from pydantic import BaseModel, Field, field_validator


class Citation(BaseModel):
    """Enforced citation linked directly to a verified chunk in the index."""

    doc_id: str = Field(..., description="Version-independent logical document path")
    chunk_id: str = Field(..., description="Unique chunk identifier e.g. v1.31:concepts/overview#c0")
    version: str = Field(..., description="Kubernetes version e.g. '1.27' or '1.31'")
    quote: str = Field(..., description="Exact verbatim substring from the chunk text")


class AskRequest(BaseModel):
    """Incoming user question request."""

    question: str = Field(..., description="User question text")
    top_k: int = Field(default=5, ge=1, le=20, description="Number of top chunks to retrieve")
    version: Optional[str] = Field(default=None, description="Optional version pin e.g. '1.27' or '1.31'")

    @field_validator("version")
    @classmethod
    def validate_version(cls, v: Optional[str]) -> Optional[str]:
        if v is not None:
            cleaned = v.strip().lstrip("v")
            if cleaned not in ("1.27", "1.31"):
                raise ValueError("Version pin must be '1.27' or '1.31'")
            return cleaned
        return None


class AskResponse(BaseModel):
    """Exact required API response schema for all /ask invocations."""

    answer: str = Field(..., description="Grounded answer text or plain-English refusal message")
    refused: bool = Field(..., description="True if query was refused, False if successfully answered")
    citations: List[Citation] = Field(default_factory=list, description="Verified citations supporting factual claims")
    retrieved_chunk_ids: List[str] = Field(default_factory=list, description="All chunk IDs passed to generator or retrieved")
    latency_ms: int = Field(..., description="Total end-to-end request latency in milliseconds")


class HealthResponse(BaseModel):
    """Health check response schema."""

    status: str = Field(default="ok", description="Service health status")
    version: str = Field(default="1.0.0", description="Service version")
    index_ready: bool = Field(default=True, description="True if vector index is loaded and ready")


class ChunkMetadata(BaseModel):
    """Metadata associated with each individual chunk."""

    doc_id: str = Field(..., description="Logical document identifier e.g. 'concepts/overview/_index'")
    version: str = Field(..., description="Kubernetes version '1.27' or '1.31'")
    chunk_id: str = Field(..., description="Chunk ID: f'v{version}:{doc_id}#c{ordinal}'")
    title: str = Field(..., description="Document title extracted from front matter or top heading")
    heading_path: str = Field(..., description="Breadcrumb heading hierarchy e.g. 'Overview > Architecture'")
    ordinal: int = Field(..., description="Zero-based ordinal index within the document")
    source_path: str = Field(..., description="Relative path in corpus e.g. 'corpus/v1.31/concepts/overview/_index.md'")


class Chunk(BaseModel):
    """Complete chunk representation with stored text and embedding text."""

    metadata: ChunkMetadata
    text: str = Field(..., description="Exact raw text stored in index/chunks.jsonl for quote verification")
    embedded_text: str = Field(..., description="Prefixed context text passed to embedding model")


class RawCitation(BaseModel):
    """Citation directly parsed from the raw LLM output before code verification."""

    chunk_id: str
    quote: str


class LLMAnswerPayload(BaseModel):
    """Parsed JSON payload generated by the LLM."""

    answer: str
    citations: List[RawCitation] = Field(default_factory=list)
    supported: bool = Field(default=False)


class EvalQuestion(BaseModel):
    """Gold evaluation question definition from eval/eval_set.jsonl."""

    qid: str
    question: str
    expected: str
    type: str
    gold_docs: List[str]
    why_this_question: str


class CorpusVersionManifest(BaseModel):
    """Manifest record for a specific version tree."""

    branch: str
    commit_sha: str
    page_count: int
    included_paths: List[str]


class CorpusManifest(BaseModel):
    """Top-level corpus manifest (corpus/MANIFEST.json)."""

    repository: str
    selection_criteria: str
    fetch_date: str
    versions: dict[str, CorpusVersionManifest]
